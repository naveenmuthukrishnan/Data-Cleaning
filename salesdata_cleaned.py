import pandas as pd
import numpy as np
import regex

"""##Importing dataset and analyzing"""

sales_2017 = pd.read_csv('/content/sales_transaction_2017.csv')
sales_2017.head()

"""##After analyzing

* Gross is the product of rate and quantity(Qty) -- dropping them since we have individual product price and qty purchased
* Disc the discount applied on the product's price and its not mentioned for all products in the dataset so dropping them
* Voucher Amount is the column that holds the total calculated price for a transaction --- it contains some null values since the total calculated was updated to the 1st product record for a sale voucher
"""

sales_2017_ = sales_2017.drop(['Gross','Disc','Voucher Amount'], axis = 1)
sales_2017_.head()

"""##Check for null and duplicates"""

sales_2017_.head(n=10)

"""* Since we can see whitespace(index 8 and 9) which mean no data record in those index (may be there a lot)
* so fillup with null values in those records
"""

sales_2017_.replace("^\s*$",np.nan,regex = True, inplace = True)
sales_2017_.head(n=10)

sales_2017_.isna().sum()

sales_2017_.dropna(inplace = True)

"""##Look at the index numbers of records"""

sales_2017_.head(n=10)

sales_2017.duplicated().sum()

sales_2017_.drop_duplicates(inplace = True)

sales_2017_.shape

sales_2017.shape

sales_2017_.duplicated().sum()

sales_2017_.isna().sum()

"""##Resetting the index change happened while cleaning data"""

sales_2017_.reset_index(drop = True, inplace = True)

sales_2017_.head(n=10)

"""##Now the shape of our data matched after cleaning"""

sales_2017_.tail(n=10)

"""##Keeping vouchers as integers"""

sales_2017_['Voucher'] = sales_2017_['Voucher'].replace('Sal:','',regex = True)
sales_2017_['Qty'] = sales_2017_['Qty'].replace(',','',regex = True)  #.str.contains().sum() is used to fetch details about this
sales_2017_['Rate'] = sales_2017_['Rate'].replace(',','',regex = True)

sales_2017_.tail()

"""##Converting to their relevant datatype of features"""

sales_2017_.info()

def dtype_conv(feature_name, dt_type):
  sales_2017_[feature_name] = sales_2017_[feature_name].astype(dt_type)

dtype_conv('Date','datetime64[ns]')
dtype_conv('Voucher','int64')
dtype_conv('Qty','float64')
dtype_conv('Rate','float64')

